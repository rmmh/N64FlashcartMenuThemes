#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePng } from '../src/png-node.mjs';
import { BORDER_NAMES } from '../src/utils.mjs';
import { quantizeImage, makePalette, mapCi4 } from '../src/texture.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const slugs = BORDER_NAMES.map(name => name.toLowerCase());
const records = [];
for (let id = 0; id < slugs.length; id++) {
  const file = path.join(root, 'assets', 'images', `theme-border-${slugs[id]}.png`);
  const image = decodePng(new Uint8Array(await fs.readFile(file)));
  if (image.width !== 24 || image.height !== 24) throw new Error(`${file} must be 24x24`);
  const quantized = quantizeImage(image);
  const texture = mapCi4(quantized, makePalette([quantized]));
  records.push({
    id,
    name: BORDER_NAMES[id],
    palette: texture.palette,
    indicesBase64: Buffer.from(texture.indices).toString('base64')
  });
}

const output = `// Generated by tools/build-internal-borders.mjs from assets/images/theme-border-*.png.\n` +
`// Do not edit by hand. These are the launcher's internal 24x24 border artworks converted to CI4.\n\n` +
`const RECORDS = ${JSON.stringify(records, null, 2)};\n\n` +
`function decodeIndices(base64) {\n` +
`  const raw = atob(base64);\n` +
`  const out = new Uint8Array(raw.length);\n` +
`  for (let i = 0; i < raw.length; i++) out[i] = raw.charCodeAt(i);\n` +
`  return out;\n` +
`}\n\n` +
`export const INTERNAL_BORDER_TEXTURES = RECORDS.map(record => Object.freeze({\n` +
`  id: record.id,\n` +
`  name: record.name,\n` +
`  width: 24,\n` +
`  height: 24,\n` +
`  kind: 'ci4',\n` +
`  palette: Object.freeze(record.palette.slice()),\n` +
`  indices: decodeIndices(record.indicesBase64)\n` +
`}));\n`;

await fs.writeFile(path.join(root, 'src', 'internal-borders.generated.mjs'), output);
console.log(`generated ${records.length} internal borders`);
